static uint32_t fnv1a_pcm(const int16_t *pcm, size_t n) {
    uint32_t h = 0x811c9dc5u;
    for (size_t i = 0; i < n; i++) {
        uint16_t u = (uint16_t)pcm[i];
        h = (h ^ (u & 0xffu)) * 0x01000193u;
        h = (h ^ (u >> 8)) * 0x01000193u;
    }
    return h;
}

static void constants_tests(void) {
    // The wire figures a server has to match, pinned: 40 ms is 640 samples, a
    // block is its header plus a nibble a sample, and the decoded size is what
    // the codec has always been fed.
    assert(AV_ADPCM_HEADER_BYTES == 4u);
    assert(AV_AUDIO_SAMPLES == 640u);
    assert(AV_AUDIO_BYTES == 324u);
    assert(AV_AUDIO_PCM_BYTES == 1280u);
    assert(sizeof(k_d) == AV_AUDIO_BYTES);
}

static void header_tests(void) {
    uint8_t h[4] = {0x12, 0x34, 0, 0};
    assert(av_adpcm_header_valid(h));
    h[2] = AV_ADPCM_INDEX_MAX; assert(av_adpcm_header_valid(h));
    h[2] = AV_ADPCM_INDEX_MAX + 1; assert(!av_adpcm_header_valid(h));
    h[2] = 255; assert(!av_adpcm_header_valid(h));
    h[2] = 0; h[3] = 1; assert(!av_adpcm_header_valid(h));
    assert(!av_adpcm_header_valid(NULL));
    // The predictor is any 16-bit value, either sign.
    h[3] = 0; h[0] = 0x80; h[1] = 0x00; assert(av_adpcm_header_valid(h));
    h[0] = 0x7f; h[1] = 0xff; assert(av_adpcm_header_valid(h));
}

static void vector_tests(void) {
    int16_t out[32];
    // Each block decodes alone: the second needs nothing from the first.
    av_adpcm_decode(k_a2, 16, out);
    assert(!memcmp(out, k_a_pcm + 16, 16 * sizeof(int16_t)));
    av_adpcm_decode(k_a1, 16, out);
    assert(!memcmp(out, k_a_pcm, 16 * sizeof(int16_t)));
    // The header of a block is the state its predecessor ended in.
    assert(k_a_pcm[15] == (int16_t)((k_a2[0] << 8) | k_a2[1]));

    av_adpcm_decode(k_b, 16, out);
    assert(!memcmp(out, k_b_pcm, sizeof(k_b_pcm)));
    av_adpcm_decode(k_c, 16, out);
    assert(!memcmp(out, k_c_pcm, sizeof(k_c_pcm)));
}

static void packet_tests(void) {
    int16_t out[AV_AUDIO_SAMPLES];
    assert(av_adpcm_header_valid(k_d));
    av_adpcm_decode(k_d, AV_AUDIO_SAMPLES, out);
    assert(out[0] == 66 && out[1] == 142 && out[2] == 307 && out[3] == 662);
    assert(out[636] == 7982 && out[637] == 12242 && out[638] == 11689 && out[639] == 7160);
    assert(fnv1a_pcm(out, AV_AUDIO_SAMPLES) == 0xb009106fu);
}

static void edge_tests(void) {
    int16_t out[16];
    // An odd count reads only the nibbles it needs and writes nothing past them.
    for (unsigned i = 0; i < 16; i++) out[i] = 0x5a5a;
    av_adpcm_decode(k_a1, 15, out);
    assert(!memcmp(out, k_a_pcm, 15 * sizeof(int16_t)));
    assert(out[15] == 0x5a5a);

    // A step index past the table is clamped, so a header that skipped the
    // validity check cannot reach outside the table; it decodes as the top entry.
    uint8_t bad[12], top[12];
    memcpy(bad, k_b, sizeof(bad)); memcpy(top, k_b, sizeof(top));
    bad[2] = 200; top[2] = AV_ADPCM_INDEX_MAX;
    int16_t a[16], b[16];
    av_adpcm_decode(bad, 16, a);
    av_adpcm_decode(top, 16, b);
    assert(!memcmp(a, b, sizeof(a)));
}

int main(void) {
    constants_tests();
    header_tests();
    vector_tests();
    packet_tests();
    edge_tests();
    puts("IMA ADPCM decoder tests: PASS");
    return 0;
}
